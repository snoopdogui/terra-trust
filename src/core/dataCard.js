// Builds the JSON-LD data card for the synthetic dataset.
//
// Vocabulary: schema.org Dataset plus terms from MLCommons Croissant (core and the Responsible AI
// extension). The @context below matches the one used by the mlcroissant reference library.
// scripts/validate-croissant.py checks a generated card with that library. The app itself does
// not run a validator, and this card makes no claim beyond that check.
//
// Pure function. No timestamps, so the card is identical for the same dataset.

import { CSV_FILE_NAME } from './datasetExport.js';
import { FARMER_COLUMNS, summariseDataset } from './datasetStats.js';
import { DATA_CATEGORIES, PURPOSES } from './constants.js';

export const CARD_FILE_NAME = 'terra-trust-data-card.jsonld';
export const LICENSE_URL = 'https://creativecommons.org/publicdomain/zero/1.0/';

const CONTEXT = {
  '@language': 'en',
  '@vocab': 'https://schema.org/',
  citeAs: 'cr:citeAs',
  column: 'cr:column',
  conformsTo: 'dct:conformsTo',
  cr: 'http://mlcommons.org/croissant/',
  rai: 'http://mlcommons.org/croissant/RAI/',
  data: { '@id': 'cr:data', '@type': '@json' },
  dataType: { '@id': 'cr:dataType', '@type': '@vocab' },
  dct: 'http://purl.org/dc/terms/',
  equivalentProperty: 'cr:equivalentProperty',
  examples: { '@id': 'cr:examples', '@type': '@json' },
  extract: 'cr:extract',
  field: 'cr:field',
  fileProperty: 'cr:fileProperty',
  fileObject: 'cr:fileObject',
  fileSet: 'cr:fileSet',
  format: 'cr:format',
  includes: 'cr:includes',
  isLiveDataset: 'cr:isLiveDataset',
  jsonPath: 'cr:jsonPath',
  key: 'cr:key',
  md5: 'cr:md5',
  parentField: 'cr:parentField',
  path: 'cr:path',
  recordSet: 'cr:recordSet',
  references: 'cr:references',
  regex: 'cr:regex',
  repeated: 'cr:repeated',
  replace: 'cr:replace',
  samplingRate: 'cr:samplingRate',
  sc: 'https://schema.org/',
  separator: 'cr:separator',
  source: 'cr:source',
  subField: 'cr:subField',
  transform: 'cr:transform',
};

const DATA_TYPE = { text: 'sc:Text', number: 'sc:Float' };

function fieldType(column) {
  if (column.dataType === 'number') return column.name === 'yieldKgHa' ? 'sc:Integer' : 'sc:Float';
  return DATA_TYPE[column.dataType];
}

/**
 * @param dataset  the synthetic dataset
 * @param options  { csvSha256 }  hash of the CSV export. Without it the card has no distribution entry.
 */
export function buildDataCard(dataset, { csvSha256 = null } = {}) {
  const s = summariseDataset(dataset);
  const meta = dataset.meta;
  const smallest = s.perCooperative.reduce((a, b) => (b.farmers < a.farmers ? b : a));
  const largest = s.perCooperative.reduce((a, b) => (b.farmers > a.farmers ? b : a));

  const card = {
    '@context': CONTEXT,
    '@type': 'sc:Dataset',
    conformsTo: 'http://mlcommons.org/croissant/1.0',
    name: 'terra-trust-synthetic-farmers',
    description:
      `Synthetic data for a proof-of-concept agricultural data trust. ${s.rows} invented cocoa farmers in ${s.cooperatives} invented cooperatives and ${s.zones} coarse zones, with yield and price for one synthetic reference season. ` +
      'Every value is generated by code from a fixed random seed. No real farmers, cooperatives, buyers or coordinates are involved, and the values are not calibrated to any real market or survey.',
    version: meta.generatorVersion,
    license: LICENSE_URL,
    citeAs: `Terra Trust synthetic farmer dataset, generator version ${meta.generatorVersion}, seed ${meta.seed}.`,
    creator: { '@type': 'sc:Organization', name: 'Terra Trust prototype contributors' },
    keywords: ['synthetic data', 'data trust', 'data governance', 'consent', 'cocoa', 'proof of concept'],
    isAccessibleForFree: true,
    inLanguage: 'en',
    conditionsOfAccess:
      'The data is synthetic and open. In the prototype, buyers can only reach it through aggregate queries that are gated by buyer purpose approval, farmer consent per data category and purpose, and a minimum group size (default 10). Direct identifiers cannot be used as filters.',
    variableMeasured: [
      {
        '@type': 'sc:PropertyValue',
        name: 'yieldKgHa',
        unitText: 'kg/ha',
        minValue: s.yield.min,
        maxValue: s.yield.max,
        description: `Mean ${s.yield.mean}, population standard deviation ${s.yield.sd}.`,
      },
      {
        '@type': 'sc:PropertyValue',
        name: 'priceGhsPerKg',
        unitText: 'GHS/kg',
        minValue: s.price.min,
        maxValue: s.price.max,
        description: `Mean ${s.price.mean}, population standard deviation ${s.price.sd}.`,
      },
    ],
    'rai:dataCollection':
      `Generated, not collected. The generator in src/core/syntheticData.js (version ${meta.generatorVersion}) draws every value from a seeded pseudo-random generator (mulberry32, seed ${meta.seed}). Cooperative sizes are fixed at ${s.perCooperative.map((c) => c.farmers).join(', ')}. Cooperatives differ only in their mean yield and mean price.`,
    'rai:dataCollectionType': ['Synthetic data generated by code from a fixed random seed'],
    'rai:dataCollectionRawData': 'There is no raw data. Nothing is derived from real records.',
    'rai:dataPreprocessingProtocol':
      'Exact age and exact plot size are generated, used to assign an age band and a plot size band, and then discarded. Only the bands are stored. Coarse zone codes stand in for plot location.',
    'rai:dataAnnotationProtocol':
      'No human or machine annotation. Each synthetic farmer is assigned a consent profile (broad, selective, cautious or withheld) by the generator, which sets that farmer\'s starting consent for each data category and purpose. Consent settings are held separately and are not part of the CSV.',
    'rai:dataUseCases':
      'Testing consent handling, query policy and evaluation harnesses for data trusts. It is not suitable for estimating real yields, prices or farmer behaviour.',
    'rai:dataBiases':
      `Cooperative sizes are unequal by design (smallest ${smallest.farmers} farmers, largest ${largest.farmers}). Zones, ages, genders, varieties and consent profiles are drawn from hand-chosen probabilities, not from observed populations, so they will not match any real group. Consent profiles are not calibrated to real behaviour. No formal bias analysis has been done.`,
    'rai:dataLimitations':
      'Not calibrated to any real market, survey or location. Values are independent draws with cooperative-level means, so they lack the correlations of real data. Quasi-identifiers (zone, age band, gender, plot size band, variety) are included on purpose so that re-identification attempts can be tested.',
    'rai:personalSensitiveInformation':
      'None. All records are invented. Gender and age band are included only as synthetic quasi-identifiers. A real dataset with these fields would be personal data and would need a legal basis and protection that this prototype does not provide.',
    'rai:dataReleaseMaintenancePlan':
      'Static. The dataset is regenerated identically from the seed and generator version and is not updated. There is no release schedule.',
  };

  if (csvSha256) {
    card.distribution = [
      {
        '@type': 'cr:FileObject',
        '@id': 'farmers-csv',
        name: 'farmers-csv',
        description: 'The synthetic farmer table as comma-separated values, one row per farmer.',
        contentUrl: CSV_FILE_NAME,
        encodingFormat: 'text/csv',
        sha256: csvSha256,
      },
    ];
    card.recordSet = [
      {
        '@type': 'cr:RecordSet',
        '@id': 'farmers',
        name: 'farmers',
        description: 'One record per synthetic farmer.',
        key: { '@id': 'farmers/id' },
        field: FARMER_COLUMNS.map((column) => ({
          '@type': 'cr:Field',
          '@id': `farmers/${column.name}`,
          name: column.name,
          description: column.description,
          dataType: fieldType(column),
          source: { fileObject: { '@id': 'farmers-csv' }, extract: { column: column.name } },
        })),
      },
    ];
  }
  return card;
}

/** Plain-language description of the consent model, shown next to the card. */
export function describeConsentModel() {
  return `${DATA_CATEGORIES.length} data categories by ${PURPOSES.length} purposes, each set to none, aggregate or per-cooperative.`;
}
